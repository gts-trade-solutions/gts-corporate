/**
 * Vehicle model schedule — the source for /vehicle-models and its detail pages.
 *
 * Every row is transcribed from the client's "GTS Vehicle Models & Components"
 * catalogue: 96 model pages across 10 sections. The catalogue supplies the model
 * name, the vehicle type, the OEM, the priority spare parts line and the vehicle
 * photograph; `exportedFrom` and `markets` carry over from the earlier export
 * schedule, and models the catalogue introduced take the market list already
 * recorded for the same OEM and segment.
 *
 * `parts` is the catalogue's "Priority Spare Parts / Components" line, split on
 * its semicolons — the wording is the client's, not ours. It is also what the
 * enquiry flow selects from: a buyer ticks the components they need on the model
 * page and arrives at the RFQ form with that selection already carried across.
 * Where the catalogue adds a qualifier for a body type, that sentence is kept
 * verbatim in `partsNote`.
 *
 * Content rule, unchanged from the rest of the site: nothing here claims stock,
 * approval, authorisation or an OEM relationship. It is a demand schedule of
 * what is asked for, not an inventory or a franchise claim.
 *
 * To add a model: append one object below and drop its photograph at
 * `public/images/vehicles/<slug>.webp`. The index page, the filters, the detail
 * page, the sitemap and the structured data all follow from it.
 */

export type VehicleModelGroupId =
  | "passenger-vehicles"
  | "two-wheelers"
  | "three-wheelers"
  | "commercial-vehicles"
  | "buses";

/** Which of the catalogue's four component photo grids a model page prints. */
export type ComponentSetId = "commercial" | "passenger" | "motorcycle" | "three-wheeler";

export type VehicleModel = {
  /** Stable URL segment — /vehicle-models/<slug>. */
  slug: string;
  oem: string;
  model: string;
  /** Vehicle type exactly as given in the catalogue. */
  segment: string;
  /** Filter group, aligned with the vehicle categories used elsewhere. */
  group: VehicleModelGroupId;
  exportedFrom: string;
  /** Destination markets this model currently moves into. */
  markets: string[];
  /** Priority spare parts — individually selectable in the enquiry flow. */
  parts: string[];
  /** Catalogue qualifier for this body type, verbatim. */
  partsNote?: string;
  components: ComponentSetId;
};

