/**
 * Vehicle model schedule — the source for /vehicle-models and its detail pages.
 *
 * Every row here comes from the client-supplied model schedule. Each model
 * carries the vehicle type, the OEM, the country it is exported from, the
 * destination markets it currently moves into, and the spare parts most often
 * requested for it. The parts list is what the enquiry flow selects from:
 * a buyer ticks the components they need on the model page and arrives at the
 * RFQ form with that selection already carried across.
 *
 * Content rule, unchanged from the rest of the site: nothing here claims stock,
 * approval, authorisation or an OEM relationship. It is a demand schedule of
 * what is asked for, not an inventory or a franchise claim.
 *
 * To add a model: append one object below. The index page, the filters, the
 * detail page, the sitemap and the structured data all follow from it.
 */

